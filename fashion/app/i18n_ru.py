SEASON = re.compile(r"\b(?:SS|FW|AW|PF|RE|PS|FS)\d{2}\b")
NUM = re.compile(r"(?<![\w#])-?\d[\d   ,.]*\d(?!\w)|(?<![\w#])\d(?!\w)")


def canon(text: str) -> tuple[str, list[str], list[str]]:
    seasons = SEASON.findall(text)
    t = SEASON.sub("{S}", text)
    nums: list[str] = []

    def num(m: re.Match) -> str:
        nums.append(m.group(0))
        return "{%d}" % (len(nums) - 1)
    return NUM.sub(num, t), seasons, nums


def translate(text: str) -> str | None:
    """The Russian for one whole UI phrase, or None (data, or not in the dictionary)."""
    raw = text.strip()
    if not raw or not re.search(r"[A-Za-z]{2}", raw) or re.search(r"[А-Яа-яЁё]", raw):
        return None
    key, seasons, nums = canon(raw)
    ru = RU.get(key)
    if ru is None:
        for pattern, repl in PATTERNS:
            m = pattern.fullmatch(raw)
            if m:
                return m.expand(repl)
        return None
    for s in seasons:
        ru = ru.replace("{S}", s, 1)
    for i, n in enumerate(nums):
        ru = ru.replace("{%d}" % i, n)
    return ru


TEXT_NODE = re.compile(r">([^<>]*[A-Za-z][^<>]*)<")
ATTR = re.compile(r'\b(title|placeholder|aria-label|value|alt)="([^"<>]*[A-Za-z][^"<>]*)"')
PROTECT = re.compile(r"<script\b.*?</script>|<style\b.*?</style>", re.S | re.I)
TEXTAREA = re.compile(r"(<textarea\b[^>]*>)(.*?)(</textarea>)", re.S | re.I)


def _node(m: re.Match) -> str:
    inner = m.group(1)
    ru = translate(html.unescape(inner))
    if ru is None:
        return m.group(0)
    lead = inner[:len(inner) - len(inner.lstrip())]
    trail = inner[len(inner.rstrip()):]
    return ">" + lead + html.escape(ru, quote=False) + trail + "<"


def _attr(m: re.Match) -> str:
    ru = translate(html.unescape(m.group(2)))
    return m.group(0) if ru is None else f'{m.group(1)}="{html.escape(ru, quote=True)}"'


def translate_html(page: str) -> str:
    """Scripts, styles and what is typed in a textarea stay as they are (kept aside as tokens without < or >)."""
    kept: list[str] = []

    def keep(text: str) -> str:
        kept.append(text)
        return f"\x00{len(kept) - 1}\x00"
    page = PROTECT.sub(lambda m: keep(m.group(0)), page)
    page = TEXTAREA.sub(lambda m: m.group(1) + keep(m.group(2)) + m.group(3), page)
    page = ATTR.sub(_attr, TEXT_NODE.sub(_node, page))
    return re.sub("\x00(\\d+)\x00", lambda m: kept[int(m.group(1))], page)
